--______Operaciones en SQL Server_______

--Lenguaje de definición de datos - DDL - Data Definition Language
 CREATE: -- Creación de objetos.
 ALTER: -- Modificación de objetos.
 DROP: -- Eliminación de objetos.


--Lenguaje de consulta de datos - DQL - Data Query Language
 SELECT: -- Las consultas de datos nos permiten recuperar la información de las tablas.


--Lenguaje de manipulación de datos - DML - Data Manipulation Language
 INSERT: -- Ingresar registros.
 UPDATE: -- Modificar los registros.
 DELETE: -- Eliminar registros.


--Comandos de control transaccional - TCL - Transaction Control Language
--BEGIN TRANSACTION: -- Inicio de la transacción.
COMMIT TRANSACTION: -- Confirmación y almacenamiento de la transacción.
ROLLBACK TRANSACTION: -- Si falla algo, deshago todo lo modificado.

REVOKE: -- Revocar permisos